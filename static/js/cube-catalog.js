/*
  Facets and the "superseded" toggle for the cube catalog table, extracted from
  an inline <script> in templates/classes/cube%3ACube.html.

  Nothing here was ever generated by Go — the block had no template actions at
  all, so this is a straight move. It stays specific to that page (the table id
  "cubeCatalog" is hard-coded, as it was before) and is only loaded from there.
*/
// Facets + superseded toggle for the catalog table. The Tabulator instance is
// published in window.visotoTables by the sparqlTable fragment once HTMX has
// swapped it in, so poll until it exists and has data.
(function() {
  var state = { includeSuperseded: false, theme: null, publisher: null };
  var table = null;

  function val(b) { return b ? (b.DisplayText || b.Value || "") : ""; }

  function rowThemes(data) {
    var t = val(data.themes);
    return t ? t.split("; ") : [];
  }

  function applyFilters() {
    table.setFilter(function(data) {
      if (!state.includeSuperseded && val(data.superseded) !== "current") return false;
      if (state.theme && rowThemes(data).indexOf(state.theme) === -1) return false;
      if (state.publisher && val(data.publisher) !== state.publisher) return false;
      return true;
    });
  }

  // Top-N values among CURRENT rows, so facet counts match the default view.
  function topCounts(rows, extract, n) {
    var counts = {};
    rows.forEach(function(data) {
      if (val(data.superseded) !== "current") return;
      extract(data).forEach(function(key) {
        if (!key) return;
        counts[key] = (counts[key] || 0) + 1;
      });
    });
    return Object.keys(counts)
      .map(function(k) { return { key: k, n: counts[k] }; })
      .sort(function(a, b) { return b.n - a.n; })
      .slice(0, n);
  }

  function renderChips(containerId, entries, stateKey) {
    var container = document.getElementById(containerId);
    entries.forEach(function(e) {
      var chip = document.createElement("a");
      chip.href = "#";
      chip.className = "badge bg-blue-lt";
      chip.textContent = e.key + " (" + e.n + ")";
      chip.addEventListener("click", function(ev) {
        ev.preventDefault();
        var active = state[stateKey] === e.key;
        state[stateKey] = active ? null : e.key;
        container.querySelectorAll(".badge").forEach(function(b) {
          b.classList.remove("bg-blue");
          b.classList.add("bg-blue-lt");
        });
        if (!active) {
          chip.classList.remove("bg-blue-lt");
          chip.classList.add("bg-blue");
        }
        applyFilters();
      });
      container.appendChild(chip);
    });
  }

  function init() {
    var rows = table.getData();
    applyFilters();

    renderChips("cube-facet-themes",
      topCounts(rows, rowThemes, 8), "theme");
    renderChips("cube-facet-publishers",
      topCounts(rows, function(d) { return [val(d.publisher)]; }, 8), "publisher");

    var supersededCount = rows.filter(function(d) {
      return val(d.superseded) !== "current";
    }).length;
    document.getElementById("cube-toggle-superseded-label").textContent =
      "Include " + supersededCount + " superseded versions";
    document.getElementById("cube-toggle-superseded")
      .addEventListener("change", function() {
        state.includeSuperseded = this.checked;
        applyFilters();
      });

    document.getElementById("cube-facets").classList.remove("d-none");
  }

  var tries = 0;
  var poll = setInterval(function() {
    table = window.visotoTables && window.visotoTables["cubeCatalog"];
    if (table && table.getData().length > 0) {
      clearInterval(poll);
      init();
    } else if (++tries > 300) {
      clearInterval(poll);
    }
  }, 300);
})();
