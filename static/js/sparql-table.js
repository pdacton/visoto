/*
  Behaviour for the "sparqlTable" partial (templates/partials/sparql-table.html):
  the Tabulator instance, working-set loading, facets, grouping and downloads.

  Extracted from two inline <script> blocks totalling ~800 lines. That code was
  the last and largest piece of JavaScript generated by a Go template in this
  project, with ~53 interpolation points. They resolved into three kinds of
  thing, all of which are now data rather than code:

    - the instance id, repeated in ~30 DOM selectors -> read once from the root
    - config scalars (working-set flags, facet id, paging, titles) -> one island
    - the query and endpoint, previously inlined with toJSONRaw -> same island

  The island is written with toJSON, which escapes < > & as \u sequences. That
  matters: a <template> re-encodes entities when read back through innerHTML, so
  the raw angle brackets toJSONRaw emits would corrupt every IRI in the query.

  Re-entrancy: this partial is swapped in by HTMX (the resource "Data" view), so
  the tag can execute again after the initial page load. boot() therefore runs on
  every execution and guards per element, rather than latching a module-level
  "already loaded" flag that would leave a freshly swapped-in table dead.
*/
(function () {
  'use strict';

  // The template set the query id is scoped to (see static/js/template-set.js).
  // Guarded like faceted-table.js's endpoint/lang readers: this file's <script>
  // sits inside the rendered card, above the shared scripts at the end of
  // <body>, so the reader is not guaranteed to be defined while it parses.
  function templateSetName() {
    return (typeof activeTemplateSet === 'function') ? activeTemplateSet() : '';
  }

  function initSparqlTable(root) {
    var CFG;
    try {
      CFG = JSON.parse(document.getElementById(root.getAttribute('data-sparql-table-config')).innerHTML.trim());
    } catch (e) {
      return;
    }
    var ID = CFG.id;
    if (!ID) return;

    // --- YASGUI "open query" action (present whether or not there are rows) ---
    var sparqlEndpointBtn = document.querySelector(".sparql-endpoint-" + ID);
    if (sparqlEndpointBtn) {
      sparqlEndpointBtn.addEventListener("click", function(e) {
        e.preventDefault();
        var query = CFG.query;
        var endpoint = CFG.endpoint;
        var url = "https://yasgui.triply.cc/#query=" + encodeURIComponent(query) + "&endpoint=" + encodeURIComponent(endpoint);
        window.open(url, "_blank");
      });
    }

    // --- Tabulator init; only when the partial rendered a table container ----
    if (!document.getElementById(ID + "-table")) return;

    var WORKING_SET = !!CFG.workingSet;

    // ---- header-attached facets (faceted tables only) ----
    // FACET_FOR is the base query id; the facet specs live in the page's
    // <sparql-facet for="<FACET_FOR>"> elements, read via the shared toolkit.
    var FACET_FOR = CFG.facetFor || "";
    var facetSpecs = (FACET_FOR && window.VisotoFacets)
      ? window.VisotoFacets.readSpecs(FACET_FOR) : [];
    // Map facet var → spec, for O(1) lookup while building columns.
    var facetByVar = {};
    facetSpecs.forEach(function (s) { facetByVar[s.name] = s; });

    // Enumerate a select facet's options from the rows already loaded, so a table
    // holding the complete population never calls /api/facet-values. That request
    // is the expensive half of faceted search — for a facet with no property path
    // the server can only enumerate by re-running the whole base query — and it is
    // pure waste when every candidate value is already on the client.
    //
    // Returns false when only the backend can answer (an incomplete working set,
    // where local values would be a subset of the truth), and null when the rows
    // simply have not landed yet — this is also called eagerly at header render,
    // and that case must retry rather than fall back to a needless fetch.
    function localFacetValues(name) {
      if (WORKING_SET && !wsBrowseComplete) return false;
      if (!table) return null;
      var rows;
      // getData() is the full loaded set, not the locally filtered view, so the
      // option list stays stable while facets narrow the table.
      try { rows = table.getData(); } catch (e) { return null; }
      if (!rows || !rows.length) return null;

      // Key by whatever matchesLocally() will compare against, or a selection made
      // here would never match a row: iri-typed enums compare the raw IRI, every
      // other type compares the displayed text.
      var useRaw = (facetByVar[name] || {}).type === "iri";
      var byValue = {}, order = [];
      rows.forEach(function (row) {
        var b = row[name];
        if (!b) return;
        var value = String((useRaw ? (b.Value || b.DisplayText) : (b.DisplayText || b.Value)) || "");
        if (!value) return;
        if (!byValue[value]) {
          byValue[value] = { value: value, label: String(b.DisplayText || b.Value || value), count: 0 };
          order.push(value);
        }
        byValue[value].count++;
      });
      // Most-frequent first, so a truncated list keeps the values that matter.
      //
      // The cap is deliberately looser than the server's 200
      // (facet.DefaultEnumerateLimit): that one bounds the cost of a DISTINCT scan
      // over the whole store, a cost this path does not pay — every value is already
      // in memory, so the only thing being bounded is checkbox rows in the DOM.
      // Holding both at 200 would silently drop values from lists that are merely
      // awkward rather than expensive (Municipality has 204 districts).
      order.sort(function (a, b) { return byValue[b].count - byValue[a].count; });
      return order.slice(0, 500).map(function (v) { return byValue[v]; });
    }

    // Reload-aware fetch init for the cacheable data routes below. A hard
    // reload only bypasses the HTTP cache for browser-initiated requests, so
    // JS fetches would otherwise keep serving data cached for up to 6h (see
    // the long note in static/js/faceted-table.js). VisotoFacets owns the
    // shared implementation; plain (non-faceted) tables don't load that file,
    // hence the inline fallback.
    var dataFetchOptions = (window.VisotoFacets && window.VisotoFacets.fetchOptions)
      ? window.VisotoFacets.fetchOptions
      : (function () {
          var isReload = false;
          try {
            var nav = performance.getEntriesByType('navigation')[0];
            isReload = nav && nav.type
              ? nav.type === 'reload'
              : !!(performance.navigation && performance.navigation.type === 1);
          } catch (e) { isReload = false; }
          return function (extra) {
            var init = extra || {};
            if (isReload) init.cache = 'reload';
            return init;
          };
        })();

    // ---- shared cell rendering / sorting ----
    function escapeHtml(text) {
      if (!text) return '';
      var div = document.createElement('div');
      div.textContent = text;
      return div.innerHTML;
    }
    function renderBinding(binding) {
      if (!binding) return '';
      if (binding.Type === 'uri') {
        var display = escapeHtml(binding.DisplayText || binding.Value);
        return '<a href="/resource?iri=' + encodeURIComponent(binding.Value) + '">' + display + '</a>';
      }
      return escapeHtml(binding.DisplayText || binding.Value);
    }
    function htmlCellFormatter(cell) { return renderBinding(cell.getValue()); }
    function plainValueAccessor(value) { return value ? (value.DisplayText || value.Value || '') : ''; }
    // Per-column header filter: cell values are binding objects, so compare
    // their plain text (same semantics as the global search box).
    function bindingHeaderFilter(headerValue, rowValue) {
      return plainValueAccessor(rowValue).toLowerCase()
        .indexOf(String(headerValue).toLowerCase()) !== -1;
    }
    function valueSorter(a, b) {
      var valA = a ? (a.DisplayText || a.Value || '') : '';
      var valB = b ? (b.DisplayText || b.Value || '') : '';
      var numA = parseFloat(valA), numB = parseFloat(valB);
      if (!isNaN(numA) && !isNaN(numB)) return numA - numB;
      return String(valA).localeCompare(String(valB));
    }
    function makeGroupByFn(field) {
      return function(data) {
        var val = data[field];
        return val ? (val.DisplayText || val.Value || '') : '';
      };
    }

    // Optional icon/badge config (emitted as <template> islands for both modes).
    var iconVarEl = document.getElementById(ID + "-icon-var");
    var iconVar = iconVarEl ? iconVarEl.innerHTML.trim() : null;
    var badgeVarEl = document.getElementById(ID + "-badge-var");
    var badgeVar = badgeVarEl ? badgeVarEl.innerHTML.trim() : null;
    var availableIcons = null;
    if (iconVar) {
      var iconsEl = document.getElementById(ID + "-available-icons");
      if (iconsEl) availableIcons = JSON.parse(iconsEl.innerHTML.trim());
    }

    function badgeCellFormatter(cell) {
      var value = cell.getValue();
      if (!value) return '';
      var uri = value.Value || '';
      var label = uri.includes('#') ? uri.split('#').pop() : uri.split('/').pop();
      var badge = '<span class="badge bg-blue-lt" style="cursor:default">' + escapeHtml(label) + '</span>';
      if (value.Type === 'uri' && uri) {
        return '<a href="/resource?iri=' + encodeURIComponent(uri) + '">' + badge + '</a>';
      }
      return badge;
    }
    function iriToName(uri) {
      try { uri = decodeURIComponent(uri); } catch(e) {}
      var name = uri.includes('#') ? uri.split('#').pop() : uri.split('/').pop();
      if (name.includes(':')) name = name.split(':').pop();
      return name;
    }
    function iconCellFormatter(cell) {
      var b = cell.getValue();
      if (!b || !b.Value) return '';
      var name = iriToName(b.Value);
      var img = '';
      if (availableIcons && availableIcons[name]) {
        img = '<img src="/static/img/resource/' + name + '.svg" width="24" height="24" alt="" style="margin-right:0.4em;vertical-align:middle;">';
      } else if (availableIcons && availableIcons[name + '.fallback']) {
        img = '<img src="/static/img/resource/' + name + '.fallback.svg" width="24" height="24" alt="" style="margin-right:0.4em;vertical-align:middle;">';
      }
      return img + renderBinding(b);
    }

    // Build column definitions from a var list + a sample row (for literal
    // detection, which drives variableHeight).
    function buildColumns(vars, sampleRow) {
      sampleRow = sampleRow || {};
      // Warn (dev aid) about declared facets whose var isn't a column: a header-
      // attached facet has nowhere to live, so it is silently skipped otherwise.
      facetSpecs.forEach(function (s) {
        if ((vars || []).indexOf(s.name) === -1) {
          console.warn('facet "' + s.name + '" has no matching column — add ?' +
            s.name + ' to the base query to attach its header control.');
        }
      });
      // Heuristic cap so one long literal can't push other columns out of view
      // (fitDataStretch otherwise sizes columns to full content width). Window
      // width, not container width: always measurable, even in hidden containers.
      // maxInitialWidth only bounds the initial fit — users can drag wider.
      var capWidth = Math.max(Math.floor(window.innerWidth / 4), 250);
      return (vars || []).map(function(varName) {
        var binding = sampleRow[varName];
        var isLiteral = binding && binding.Type === 'literal';
        var isBadge = badgeVar && varName === badgeVar;
        var isIcon = iconVar && varName === iconVar;
        var facetSpec = facetByVar[varName];
        var col = {
          title: varName,
          field: varName,
          formatter: isIcon ? iconCellFormatter : (isBadge ? badgeCellFormatter : htmlCellFormatter),
          variableHeight: isLiteral,
          maxInitialWidth: capWidth,
          sorter: valueSorter,
          accessorDownload: plainValueAccessor,
          // Filter row is hidden until toggled via the card-header button
          // (.vs-show-header-filters, see tabulator_overrides.css)
          headerFilter: "input",
          headerFilterFunc: bindingHeaderFilter
        };
        // Facetable column: render a funnel dropdown in its header (portal
        // mechanics live in VisotoFacets.headerFormatter). The facet control
        // filters locally (instant) and, when the set is incomplete, fetches
        // the full-class truth from the backend (see scheduleApplyFacets).
        if (facetSpec) {
          col.titleFormatter = window.VisotoFacets.headerFormatter(facetSpec, {
            tableId: ID,
            facetFor: FACET_FOR,
            iri: CFG.iri,
            localValues: localFacetValues,
            onChange: scheduleApplyFacets
          });
          // headerSort stays enabled (default): a title click sorts, a funnel
          // click filters. The funnel handler stopPropagation()s, so clicking
          // it never also triggers a sort.
        }
        // Capped literal cells wrap and are clamped to a few lines (see
        // .vs-cell-wrap in tabulator_overrides.css); the full text is shown
        // in a hover tooltip, but only when the clamp actually hides content.
        if (isLiteral) {
          col.cssClass = "vs-cell-wrap";
          col.tooltip = function(e, cell) {
            var el = cell.getElement();
            // "" suppresses the tooltip; false would render a literal "false"
            // (Tabulator 6.3.1 treats false as content, see its loadTooltip)
            if (el.scrollHeight <= el.clientHeight + 1) return "";
            return plainValueAccessor(cell.getValue());
          };
        }
        return col;
      });
    }

    // Map a list of SPARQL binding rows ({var: binding}) to Tabulator rows.
    function toTableData(vars, bindings) {
      return (bindings || []).map(function(binding) {
        var row = {};
        vars.forEach(function(v) { row[v] = binding[v] || null; });
        return row;
      });
    }

    var paginationLangs = {
      "default": { "pagination": {
        "first": "<i data-lucide='chevrons-left'></i>", "first_title": vsT("js.table.firstPage", "First Page"),
        "prev": "<i data-lucide='chevron-left'></i>", "prev_title": vsT("js.table.prevPage", "Prev Page"),
        "next": "<i data-lucide='chevron-right'></i>", "next_title": vsT("js.table.nextPage", "Next Page"),
        "last": "<i data-lucide='chevrons-right'></i>", "last_title": vsT("js.table.lastPage", "Last Page")
      }}
    };

    // Base config shared by both modes: local pagination/sort over the loaded
    // rows. fitColumns keeps layout O(columns) — important for a 20k working set
    // (fitData* measures every cell and janks). Inline (small) tables use
    // fitDataStretch: content-sized columns, last column stretches to fill the
    // card. NOT fitDataFill — it re-runs layout on mouseup and discards manual
    // column resizes (Tabulator 6.3.1).
    function baseConfig(layout) {
      return {
        layout: layout,
        renderHorizontal: "virtual",
        renderVertical: "virtual",
        movableColumns: true,
        sortMode: "local",
        pagination: "local",
        paginationSize: 10,
        paginationSizeSelector: [10, 50, 100],
        paginationCounter: "rows",
        langs: paginationLangs
      };
    }

    var table;

    // ---- INLINE mode: rows embedded in <template> islands ----
    if (!WORKING_SET) {
      var vars = JSON.parse(document.getElementById(ID + "-vars").innerHTML.trim());
      var bindings = JSON.parse(document.getElementById(ID + "-bindings").innerHTML.trim());
      var cfg = baseConfig("fitDataStretch");
      cfg.data = toTableData(vars, bindings);
      cfg.columns = buildColumns(vars, bindings[0]);
      // Small tables don't need a pager.
      if (bindings.length <= 10) { cfg.pagination = false; }
      table = new Tabulator("#" + ID + "-table", cfg);
    } else {
      // ---- WORKING-SET mode: fetch a bounded set once, then all-local ----
      var cfg = baseConfig("fitColumns");
      cfg.data = [];
      cfg.columns = [];
      table = new Tabulator("#" + ID + "-table", cfg);
    }

    // Registry so page templates can reach the instance (facet chips, filters).
    window.visotoTables = window.visotoTables || {};
    window.visotoTables[ID] = table;

    table.on("tableBuilt", function() { if (window.lucide) lucide.createIcons(); });
    table.on("renderComplete", function() { if (window.lucide) lucide.createIcons(); });

    // Mark clamped literal cells whose content is actually hidden, so the CSS
    // fade-out indicator only appears on truly truncated cells.
    function markClippedCells() {
      document.querySelectorAll("#" + ID + "-table .tabulator-cell.vs-cell-wrap").forEach(function(el) {
        el.classList.toggle("vs-clipped", el.scrollHeight > el.clientHeight + 1);
      });
    }
    table.on("renderComplete", markClippedCells);
    table.on("columnResized", markClippedCells);
    // Keep the status bar + "Clear all" chip in sync with per-column header-
    // filters (they don't route through applyLocalFilter). renderStatus is a
    // hoisted function declaration, so it exists by the time this event fires.
    table.on("dataFiltered", function() { renderStatus(); });

    // Tabulator 6.3.1 keeps a shown tooltip open after the mouse leaves the
    // cell (its mouseoutCheck only cancels pending tooltips); hide it via the
    // tooltip module's own cleanup path.
    table.on("cellMouseOut", function() {
      if (table.modules && table.modules.tooltip) table.modules.tooltip.clearPopup();
    });

    // A table built inside a collapsed (display:none) card has no measurable
    // height, so the virtual renderer paints zero rows. Redraw once when the
    // card is first expanded so the rows appear. Guarded so a user toggling the
    // card repeatedly only pays for the first, corrective redraw.
    (function() {
      var collapseEl = document.getElementById("collapse-" + ID);
      if (!collapseEl) return;
      var didInitialRedraw = false;
      collapseEl.addEventListener("shown.bs.collapse", function onShown() {
        if (didInitialRedraw) return;
        didInitialRedraw = true;
        table.redraw(true);
      });
    })();

    // ================= WORKING-SET data loading =================
    // The endpoint slug and the language travel in the config rather than being
    // resolved here: these plain fetch()es aren't covered by the
    // htmx:configRequest hook, and the fragment is cached keyed by its own
    // ?endpoint=&lang=, so reusing the same values keeps the data requests
    // cache-keyed identically.
    // src is the exception: it names the template set the query id is scoped to,
    // which is a property of the page rather than of this fragment, so it is read
    // live instead of being carried in the config.
    var wsBaseUrl = "/api/async-table-data/" + encodeURIComponent(ID) +
      "?iri=" + encodeURIComponent(CFG.iri || "") +
      "&keyVar=" + encodeURIComponent(CFG.keyVar || "") +
      "&max=" + encodeURIComponent(CFG.max || "") +
      "&src=" + encodeURIComponent(templateSetName());
    if (CFG.searchProp) wsBaseUrl += "&searchProp=" + encodeURIComponent(CFG.searchProp);
    if (CFG.endpointSlug) wsBaseUrl += "&endpoint=" + encodeURIComponent(CFG.endpointSlug);
    // Explicit null/undefined test, not truthiness: "" is the real "no language"
    // code and must still be sent, since an absent lang= means "server default".
    // It is null on fragments rendered by a path that sets no language (the sync
    // sparqlTable partial), where falling back to the default is right.
    if (CFG.lang !== undefined && CFG.lang !== null) {
      wsBaseUrl += "&lang=" + encodeURIComponent(CFG.lang);
    }
    var wsColumnsSet = false;
    var wsSearchTerm = "";           // active backend search ("" = browse)
    var wsFaceted = false;           // whether the loaded set came from a backend facet query
    var wsLastFacetURL = "";         // URL of the currently-loaded faceted result; dedupes
                                     // identical re-applies (e.g. a text facet re-firing
                                     // its change event on blur when nothing changed)
    // wsComplete: whether the CURRENTLY loaded set is the whole in-scope population
    // (drives the banner). It is transiently true for a complete *faceted* result,
    // so it must NOT gate whether a NEW facet needs the backend — see wsBrowseComplete.
    var wsComplete = !!CFG.complete;
    // wsBrowseComplete: whether the UNFILTERED browse working set holds the entire
    // class. Only then can local filtering answer any facet authoritatively without
    // a backend fetch. Set exclusively from a browse (non-faceted) load; a complete
    // faceted result must never flip it (that set is a filtered subset, not the class).
    var wsBrowseComplete = !!CFG.complete;
    var wsTotal = CFG.total || 0;
    var wsLoaded = 0;                // rows in the currently loaded set (banner counts)
    var wsBusyMsg = "";              // non-empty while a backend request is in flight
    var wsErrorMsg = "";             // sticky failure message until the next load starts

    var bannerEl = document.getElementById("ws-banner-" + ID);
    var bannerTextEl = document.getElementById("ws-banner-text-" + ID);
    var bannerIconEl = document.getElementById("ws-banner-icon-" + ID);
    var resetChipEl = document.getElementById("ws-reset-" + ID);
    var searchAllBtn = document.getElementById("search-all-" + ID);
    var searchAllLabel = document.getElementById("search-all-label-" + ID);
    var groupBySelect = document.getElementById("groupby-" + ID);

    function fmtNum(n) { return (n != null) ? Number(n).toLocaleString() : "?"; }

    // ================= status bar (single writer) =================
    // renderStatus is the ONE writer of the working-set status bar — visibility,
    // text, busy strip (info ⇄ loader glyph), and the "Clear all" chip. Every
    // path that changes what the bar should say mutates the ws* state vars and
    // calls this; nothing else touches the banner DOM. That closes the stale-
    // message class of bug where an in-flight text written by one path
    // ("Searching…") survived a hide/re-show by another.
    //
    // Message precedence: in-flight (wsBusyMsg) > failure (wsErrorMsg) >
    // resolved state derived from wsFaceted / wsSearchTerm / wsComplete /
    // wsLoaded / wsTotal. A complete unfiltered browse hides the bar entirely —
    // unless something is filtering locally, in which case the bar stays
    // visible as the home of the "Clear all" chip.
    function renderStatus() {
      if (!bannerEl) return;
      var busy = wsBusyMsg !== "";
      var active = anyFilterActive();
      var text, visible = true;
      if (busy) {
        text = wsBusyMsg;
      } else if (wsErrorMsg) {
        text = wsErrorMsg;
      } else if (wsFaceted) {
        // Backend faceted result: a facet is necessarily active, so the bar
        // stays visible (chip home) and reports the truthful full-class count.
        text = wsComplete
          ? vsTf("js.table.showingAllMatches", "Showing all {n} full-class matches.",
                 { n: fmtNum(wsLoaded) })
          : vsTf("js.table.showingFirstMatches",
                 "Showing the first {n} full-class matches — narrow the facets to see them all.",
                 { n: fmtNum(wsLoaded) });
      } else if (wsSearchTerm) {
        text = vsTf("js.table.showingFirstMatchesFor",
          "Showing the first {n} full-class matches for “{term}” — refine your search to narrow further.",
          { n: fmtNum(wsLoaded), term: wsSearchTerm });
      } else if (!wsComplete) {
        text = vsTf("js.table.showingOf",
          "Showing {n} of {total} — filter a column or use “Search all” to reach the full class.",
          { n: fmtNum(wsLoaded), total: fmtNum(wsTotal) });
      } else if (active) {
        text = vsT("js.table.filtered", "Filtered."); // complete set, locally narrowed — bar hosts the chip
      } else {
        text = "";
        visible = false;
      }
      bannerEl.classList.toggle("d-none", !visible);
      bannerEl.classList.toggle("vs-ws-busy", busy);
      if (bannerTextEl) bannerTextEl.textContent = text;
      if (bannerIconEl) {
        bannerIconEl.innerHTML = busy
          ? '<i data-lucide="loader-circle" style="width: 1em; height: 1em;"></i>'
          : '<i data-lucide="info" style="width: 1em; height: 1em;"></i>';
      }
      if (resetChipEl) resetChipEl.classList.toggle("d-none", !active);
      if (visible && window.lucide) lucide.createIcons({ nodes: [bannerEl] });
    }

    function updateSearchAllLabel() {
      if (!searchAllLabel) return;
      searchAllLabel.textContent = wsSearchTerm
        ? ("Searching all " + fmtNum(wsTotal))
        : vsTf("js.table.searchAllN", "Search all {total}", { total: fmtNum(wsTotal) });
    }

    // Fetch a working set (browse or search) and load it into the table.
    function loadWorkingSet(term) {
      var url = wsBaseUrl;
      if (term) url += "&search=" + encodeURIComponent(term);
      // Backend request in flight → activity indicator with an in-flight message.
      wsBusyMsg = term
        ? vsTf("js.table.searchingAllFor", "Searching all instances for “{term}”…", { term: term })
        : vsT("js.table.loading", "Loading…");
      wsErrorMsg = "";
      renderStatus();
      return fetch(url, dataFetchOptions({ headers: { "Accept": "application/json" } }))
        .then(function(r) { return r.json(); })
        .then(function(resp) {
          if (resp.error) { console.warn("working-set error:", resp.error); }
          var vars = resp.vars || [];
          var rows = toTableData(vars, resp.data || []);
          if (!wsColumnsSet && vars.length) {
            table.setColumns(buildColumns(vars, (resp.data || [])[0]));
            wsColumnsSet = true;
            populateGroupBy(vars);
          }
          if (typeof resp.total === "number") wsTotal = resp.total;
          wsComplete = !!resp.complete;
          // Only an UNFILTERED browse (no search term) tells us whether the whole
          // class fits locally. A complete *search* result covers only its matches,
          // so it must not license skipping the backend for other facet terms.
          if (!term) wsBrowseComplete = !!resp.complete;
          wsSearchTerm = term || "";
          wsFaceted = false;            // this is a plain browse/search set, not faceted
          wsLastFacetURL = "";          // left faceted mode; a later facet must re-fetch
          wsLoaded = rows.length;
          wsBusyMsg = "";
          table.setData(rows);          // local pagination/sort/search from here
          table.clearFilter();
          // Re-apply any active header-facet + search local filter over the new rows.
          if (typeof applyLocalFilter === "function") applyLocalFilter();
          renderStatus();
          updateSearchAllLabel();
          // The escalation button only makes sense while the set is incomplete.
          if (searchAllBtn) {
            if (!wsComplete && currentTerm()) searchAllBtn.classList.remove("d-none");
            else searchAllBtn.classList.add("d-none");
          }
          return rows;
        })
        .catch(function(e) {
          console.warn("working-set fetch failed:", e);
          wsBusyMsg = "";
          wsErrorMsg = vsT("js.table.failedToLoad", "Failed to load data.");
          renderStatus();
        });
    }

    // Group-by options are unknown until the first working-set response.
    function populateGroupBy(vars) {
      if (!groupBySelect || !groupBySelect.dataset.wsGroupby) return;
      if (groupBySelect.options.length > 1) return; // already populated
      vars.forEach(function(v) {
        var opt = document.createElement("option");
        opt.value = v; opt.textContent = v;
        groupBySelect.appendChild(opt);
      });
    }

    if (WORKING_SET) {
      loadWorkingSet("");
    }

    // ================= unified local filter (search box + header facets) =================
    // One Tabulator function-filter combines the global search term AND every active
    // header facet. setFilter(fn) REPLACES all function filters, so the two must be
    // ANDed into a single predicate rather than set independently ("compose, don't
    // compete"). Runs instantly over the loaded rows for both inline and working-set
    // data; for a complete working set it is the final answer.
    function currentTerm() {
      var el = document.getElementById("search-" + ID);
      return el ? el.value.trim() : "";
    }

    // Snapshot the active facet selections (skipping empty ones).
    // Live facet-control nodes for THIS table. Two reasons to query the whole
    // document by a table-scoped tag rather than caching nodes or scoping to the
    // table element: (1) Tabulator re-renders header DOM (virtual header), so a
    // cached node detaches from what the user clicks; (2) an open facet menu is
    // portaled to <body> (to escape the header's overflow:hidden clip), so it lives
    // outside the table subtree while open.
    function liveFacetControls() {
      return Array.prototype.slice.call(
        document.querySelectorAll('.vs-facet[data-facet-table="' + ID + '"]'));
    }

    function activeFacetSelections() {
      if (!window.VisotoFacets) return [];
      return liveFacetControls()
        .map(window.VisotoFacets.readSelection)
        .filter(window.VisotoFacets.isActive);
    }

    function applyLocalFilter() {
      // Keep the status bar + reset chip in sync on every search/facet change
      // (both the early-return and the filter-set paths reach here).
      renderStatus();
      var term = currentTerm().toLowerCase();
      var facets = activeFacetSelections();
      if (!term && !facets.length) { table.clearFilter(); return; }
      table.setFilter(function (data) {
        // Global search: any cell contains the term.
        if (term) {
          var hit = false;
          for (var key in data) {
            var b = data[key];
            if (b && String(b.DisplayText || b.Value || '').toLowerCase().indexOf(term) !== -1) { hit = true; break; }
          }
          if (!hit) return false;
        }
        // Header facets: every active facet must match (AND across facets).
        for (var i = 0; i < facets.length; i++) {
          var sel = facets[i];
          if (!window.VisotoFacets.matchesLocally(sel, data[sel.name])) return false;
        }
        return true;
      });
    }

    // ================= reset ("Clear all") =================
    // Whether anything is currently narrowing the table: the global search box,
    // any funnel facet, or any per-column header-filter. Drives the reset chip.
    function anyColumnHeaderFilter() {
      // renderStatus runs as early as the first load start, before Tabulator
      // finishes initializing — getHeaderFilters() would log a "Table Not
      // Initialized" warning then (it doesn't throw), so gate on the flag.
      if (!table.initialized) return false;
      try { return (table.getHeaderFilters() || []).length > 0; } catch (e) { return false; }
    }
    function anyFilterActive() {
      return !!currentTerm() || activeFacetSelections().length > 0 || anyColumnHeaderFilter();
    }

    // Clear the search box + every funnel facet + all column header-filters, then
    // return to the clean browse working set. Sort and group-by are left as-is
    // (view preferences, not search). One combined apply → at most one backend
    // load, rather than one per cleared control.
    function resetAllFilters() {
      // Whether the loaded rows currently come from the server (a facet result or a
      // full-class search) — decided BEFORE we clear the state below.
      var loadedFromServer = wsFaceted || !!wsSearchTerm;
      var searchEl = document.getElementById("search-" + ID);
      if (searchEl) searchEl.value = "";
      if (window.VisotoFacets) {
        liveFacetControls().forEach(window.VisotoFacets.clearControl);
      }
      try { table.clearHeaderFilter(); } catch (e) {}
      wsSearchTerm = "";
      wsFaceted = false;
      wsLastFacetURL = "";
      if (searchAllBtn) searchAllBtn.classList.add("d-none");
      // If the on-screen rows are a server-fetched subset, reload the unfiltered
      // browse set; otherwise the whole class is already loaded locally, so just
      // drop the local filter (applyLocalFilter re-renders the status bar).
      if (WORKING_SET && loadedFromServer) {
        loadWorkingSet("");
      } else {
        applyLocalFilter();          // clears the Tabulator filter (nothing active now)
      }
    }
    if (resetChipEl) {
      resetChipEl.addEventListener("click", function (e) {
        e.preventDefault();
        resetAllFilters();
      });
    }

    // ================= two-tier facet engine (local preview + backend authority) ====
    // Presentation params passed through to the backend faceted query so its result
    // columns/labels match the browsed table.
    // Only non-empty values are sent, mirroring the per-key conditional
    // guards this object used to be assembled with server-side.
    var facetPassthrough = {};
    ["title", "icon", "iconVar", "badgeVar", "groupBy", "max"].forEach(function (k) {
      if (CFG[k]) facetPassthrough[k] = CFG[k];
    });
    var facetDebounce;
    // Debounced entry point every facet control calls on change.
    function scheduleApplyFacets() {
      // 1) Instant local preview over the loaded rows — always.
      applyLocalFilter();
      // 2) Backend authority — only when the browse working set is an incomplete
      //    sample, so local filtering can't see the full class. Gate on
      //    wsBrowseComplete (NOT wsComplete): a complete *faceted* result sets
      //    wsComplete=true, but the loaded rows are still just that facet's matches,
      //    so a different facet term must re-query the backend. Debounced to bound
      //    requests.
      if (!WORKING_SET || wsBrowseComplete) return;
      // Immediately signal the preview→backend hand-off: the rows on screen are a
      // local preview, and the authoritative full-class result is being fetched.
      // Only when something is actually constrained (an empty selection just
      // returns to the browse set, no fetch). Busy on now; loadFacetedSet keeps
      // it on through the debounce+fetch and clears it when the result lands.
      if (activeFacetSelections().length) {
        wsBusyMsg = vsT("js.table.previewing", "Previewing loaded rows — fetching full-class results…");
        wsErrorMsg = "";
        renderStatus();
      }
      clearTimeout(facetDebounce);
      facetDebounce = setTimeout(loadFacetedSet, 400);
    }

    // Fetch the true full-class matches for the active facets and load them under the
    // one Tabulator instance (setData), reusing the completeness banner.
    function loadFacetedSet() {
      if (!window.VisotoFacets) return;
      var active = activeFacetSelections();
      if (!active.length) {
        // Nothing constrains anymore → back to the plain browse working set.
        if (wsSearchTerm || wsFaceted) { wsFaceted = false; wsLastFacetURL = ""; loadWorkingSet(""); }
        else { wsBusyMsg = ""; renderStatus(); } // clear any lingering activity indicator
        return;
      }
      var url = window.VisotoFacets.buildFacetURL(FACET_FOR, CFG.iri, liveFacetControls(), facetPassthrough);
      // Dedupe: if the active selections produce the exact same query we already
      // requested (in flight OR loaded), don't re-fetch. A text facet re-fires its
      // change event on blur (e.g. clicking above the table) with an unchanged
      // value; without this that would run an identical backend search again.
      // Compare against wsLastFacetURL, which is set BEFORE the fetch (not on
      // resolve) so a re-fire while the first request is still in flight is caught.
      if (url === wsLastFacetURL) { wsBusyMsg = ""; renderStatus(); return; }
      wsFaceted = true;
      wsLastFacetURL = url;       // mark this query as requested (dedupes re-fires)
      // Backend request in flight → activity indicator on (scheduleApplyFacets
      // may already have shown it; this keeps it on across the debounce).
      wsBusyMsg = vsTf("js.table.searchingAllOnServer", "Searching all {total} on the server…", { total: fmtNum(wsTotal) });
      wsErrorMsg = "";
      renderStatus();
      fetch(url, dataFetchOptions({ headers: { "Accept": "application/json" } }))
        .then(function (r) { return r.json(); })
        .then(function (resp) {
          if (resp.error) { console.warn("faceted fetch error:", resp.error); }
          var vars = resp.vars || [];
          var rows = toTableData(vars, resp.data || []);
          wsComplete = !!resp.complete;
          wsSearchTerm = "";
          wsLoaded = rows.length;
          wsBusyMsg = "";
          table.setData(rows).then(function () {
            // Re-apply the local search term over the backend result (facets are
            // already reflected server-side; the search box is client-only).
            applyLocalFilter();
          });
          // Resolved → renderStatus derives the wsFaceted banner text (truthful
          // full-class match count, complete or capped).
          renderStatus();
        })
        .catch(function (e) {
          console.warn("faceted fetch failed:", e);
          wsLastFacetURL = ""; // allow the same facets to be retried after a failure
          wsBusyMsg = "";
          wsErrorMsg = vsT("js.table.failedToLoadMatches", "Failed to load matches.");
          renderStatus();
        });
    }

    // ================= search (local filter + optional backend rebuild) =================

    var searchInput = document.getElementById("search-" + ID);
    if (searchInput) {
      var searchTimeout;
      searchInput.addEventListener("input", function(e) {
        clearTimeout(searchTimeout);
        searchTimeout = setTimeout(function() {
          // Instant local filter over the currently loaded rows — combines the
          // search term with any active header facets into one predicate (works
          // the same for inline and working-set data).
          applyLocalFilter();
          // In working-set mode, reveal the backend-rebuild button whenever the
          // set is incomplete and there's a term (local filtering can only see
          // the loaded subset). When the term is cleared, drop back to browse.
          if (WORKING_SET && searchAllBtn) {
            if (!wsComplete && currentTerm()) {
              searchAllBtn.classList.remove("d-none");
            } else {
              searchAllBtn.classList.add("d-none");
              if (wsSearchTerm) loadWorkingSet(""); // return to browse working set
            }
          }
        }, 150);
      });
    }

    if (searchAllBtn) {
      searchAllBtn.addEventListener("click", function(e) {
        e.preventDefault();
        loadWorkingSet(currentTerm()); // rebuild the working set from the server
      });
    }

    // ================= per-column header filters =================
    var toggleFiltersBtn = document.getElementById("toggle-filters-" + ID);
    var toggleFiltersLabel = document.getElementById("toggle-filters-label-" + ID);
    var filtersShown = false;
    if (toggleFiltersBtn) {
      toggleFiltersBtn.addEventListener("click", function(e) {
        e.preventDefault();
        filtersShown = !filtersShown;
        document.getElementById(ID + "-table")
          .classList.toggle("vs-show-header-filters", filtersShown);
        if (toggleFiltersLabel) {
          toggleFiltersLabel.textContent = filtersShown
            ? vsT("js.table.hideColumnFilters", "Hide column filters")
            : vsT("js.table.showColumnFilters", "Show column filters");
        }
        // Clear on hide so rows are never invisibly filtered by hidden inputs
        if (!filtersShown) table.clearHeaderFilter();
        // Plain redraw remeasures the header height; redraw(true) would re-run
        // fitDataStretch layout and discard manual column widths.
        table.redraw();
      });
    }

    // ================= group-by (local, with localStorage) =================
    var toggleGroupsBtn = document.getElementById("toggle-groups-" + ID);
    var groupsExpanded = true;
    function setToggleBtnState(expanded) {
      groupsExpanded = expanded;
      var iconName = expanded ? "list-chevrons-down-up" : "list-chevrons-up-down";
      toggleGroupsBtn.title = expanded
        ? vsT("js.table.collapseAllGroups", "Collapse all groups")
        : vsT("js.table.expandAllGroups", "Expand all groups");
      toggleGroupsBtn.innerHTML = '<i data-lucide="' + iconName + '"></i>';
      if (window.lucide) lucide.createIcons({ nodes: [toggleGroupsBtn] });
    }
    if (toggleGroupsBtn) {
      toggleGroupsBtn.addEventListener("click", function() {
        var newExpanded = !groupsExpanded;
        table.blockRedraw();
        try {
          table.getGroups().forEach(function(group) {
            newExpanded ? group.show() : group.hide();
          });
        } finally {
          table.restoreRedraw();
        }
        setToggleBtnState(newExpanded);
      });
    }

    if (groupBySelect) {
      function applyGroupBy(field) {
        if (field === "") {
          table.setGroupBy(false);
          if (toggleGroupsBtn) toggleGroupsBtn.classList.add("d-none");
        } else {
          table.setGroupBy(makeGroupByFn(field));
          if (toggleGroupsBtn) {
            toggleGroupsBtn.classList.remove("d-none");
            setToggleBtnState(true);
          }
        }
      }
      table.on("tableBuilt", function() {
        // Author-provided initial grouping; an explicit user choice saved in
        // localStorage (including "" = no grouping) takes precedence.
        var initialGroupBy = CFG.groupBy || "";
        try {
          var savedGroupBy = localStorage.getItem("tabulator-groupby-" + ID);
          if (savedGroupBy !== null && (!groupBySelect.dataset.wsGroupby)) {
            initialGroupBy = savedGroupBy;
          }
        } catch (e) { console.warn("localStorage unavailable:", e); }
        if (initialGroupBy !== "") {
          groupBySelect.value = initialGroupBy;
          applyGroupBy(initialGroupBy);
        }
      });
      groupBySelect.addEventListener("change", function(e) {
        applyGroupBy(e.target.value);
        try { localStorage.setItem("tabulator-groupby-" + ID, e.target.value); }
        catch (e) { console.warn("localStorage unavailable:", e); }
      });
    }

    // ================= downloads (loaded rows) =================
    var filename = CFG.title || ID;
    var csvBtn = document.querySelector(".download-csv-" + ID);
    if (csvBtn) csvBtn.addEventListener("click", function(e){ e.preventDefault(); table.download("csv", filename + ".csv", { bom: true }); });
    var jsonBtn = document.querySelector(".download-json-" + ID);
    if (jsonBtn) jsonBtn.addEventListener("click", function(e){ e.preventDefault(); table.download("json", filename + ".json"); });
    var xlsxBtn = document.querySelector(".download-xlsx-" + ID);
    if (xlsxBtn) xlsxBtn.addEventListener("click", function(e){ e.preventDefault(); table.download("xlsx", filename + ".xlsx", { sheetName: filename.substring(0, 31) }); });
  }

  function boot() {
    document.querySelectorAll('[data-sparql-table]').forEach(function (root) {
      if (root.__visotoSparqlTableInit) return;
      root.__visotoSparqlTableInit = true;
      initSparqlTable(root);
    });
  }

  // This tag sits in the middle of the body, above the Tabulator CDN script that
  // base.html loads at the end, so booting immediately during the initial parse
  // would run before Tabulator exists. Wait for DOMContentLoaded in that case.
  //
  // When the document is already complete the wait is not just unnecessary but
  // wrong: HTMX swaps this partial in as a fragment (the resource "Data" view)
  // long after DOMContentLoaded has fired, and it will never fire again.
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else {
    boot();
  }
})();
